// Android device keys and Android stream handles live in their own IPC namespace.
function toolInvoke<T extends (key: string, ...args: any[]) => any>(channel: string) {
  const android = invoke<T>('android:' + channel)
  const harmony = invoke<T>(channel)
  return ((key: string, ...args: any[]) =>
    (key.startsWith('android:') ? android : harmony)(key, ...args)) as (...args: Parameters<T>) => Promise<Awaited<ReturnType<T>>>
}

